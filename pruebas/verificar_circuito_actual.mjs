import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'
import {PGlite} from '@electric-sql/pglite'

// Exportación privada de auditoria_arranque_diciembre.sql. Nunca usa la base real.
const archivo = process.env.CIBUSPAN_ESQUEMA_ACTUAL
if (!archivo) throw new Error('Define CIBUSPAN_ESQUEMA_ACTUAL con el JSON privado del diagnóstico.')
const contenido = JSON.parse((await readFile(archivo, 'utf8')).replace(/^\uFEFF/, ''))
const esquema = contenido.rows?.[0]?.auditoria_arranque_diciembre ?? contenido
assert.equal(esquema.tipo, 'auditoria_arranque_diciembre')
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`
const nombre = s => '"' + s.replaceAll('"', '""') + '"'

test('Circuito aislado con funciones actuales: pedido, plan, consumo y despacho', async t => {
  const db = new PGlite()
  try {
    await db.exec(`set check_function_bodies=false;
      create role anon; create role authenticated; create role service_role;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql as $$select '${id(1)}'::uuid$$;
      grant usage on schema public,auth to authenticated,service_role;`)
    const tablas = esquema.objetos.filter(o => o.tipo === 'r')
    for (const o of tablas) {
      const columnas = o.columnas.map(c => {
        const defecto = c.identidad || c.default?.startsWith('nextval(')
          ? ' generated by default as identity' : c.default ? ' default ' + c.default : ''
        return `${nombre(c.nombre)} ${c.tipo}${defecto}${c.no_nulo ? ' not null' : ''}`
      })
      await db.exec(`create table ${nombre(o.nombre)} (${columnas.join(',')})`)
      for (const c of o.restricciones ?? []) if (['p','u','c'].includes(c.tipo)) {
        await db.exec(`alter table ${nombre(o.nombre)} add constraint ${nombre(c.nombre)} ${c.definicion}`)
      }
    }
    const disponibles = new Set(tablas.map(o => o.nombre))
    for (const o of tablas) for (const c of o.restricciones ?? []) if (c.tipo === 'f') {
      const destino = /REFERENCES (?:public\.)?([a-z_]+)\(/.exec(c.definicion)?.[1]
      if (disponibles.has(destino) || c.definicion.includes('REFERENCES auth.users(')) {
        await db.exec(`alter table ${nombre(o.nombre)} add constraint ${nombre(c.nombre)} ${c.definicion}`)
      }
    }
    // FK de categorías y otros módulos, RLS y permisos globales no se modelan aquí.
    // Los cuerpos operativos y sus triggers se ejecutan sin modificarlos.
    for (const f of esquema.funciones) await db.exec(f.definicion)
    await db.exec(`create or replace function app_puede_alguna(p_pantallas text[]) returns boolean language sql as $$select true$$`)
    const vistas = esquema.objetos.filter(o => o.tipo === 'v')
    for (const n of ['stock_disponible_lotes','stock_semielaborados','stock_semielaborados_resumen','cm_detalles_demanda']) {
      const o = vistas.find(x => x.nombre === n)
      if (o) await db.exec(`create view ${nombre(n)} as ${o.vista.replace(/;\s*$/, '')}`)
    }
    for (const o of tablas) for (const tr of o.triggers ?? []) {
      assert.equal(tr.habilitado, 'O', `Trigger deshabilitado: ${o.nombre}.${tr.nombre}`)
      await db.exec(tr.definicion)
    }
    await db.exec(`insert into auth.users values('${id(1)}');
      insert into app_profiles(user_id,email,nombre,rol,activo) values('${id(1)}','ensayo@example.com','Ensayo','ADMINISTRADOR',true);
      insert into clientes(id,nombre,activo) values('${id(2)}','Cliente ensayo',true);
      insert into bodegas(id,cliente_id,nombre,activo) values('${id(3)}','${id(2)}','Bodega ensayo',true);
      insert into productos(id,codigo,nombre,corto,activo,tamano_lote,stock_minimo,vida_util_dias)
        values('${id(10)}','ENSAYO','Pan ensayo','Ensayo',true,10,0,30);
      insert into cliente_productos(cliente_id,producto_id,unidad_manejo,activo) values('${id(2)}','${id(10)}',10,true);
      insert into materias_primas(id,codigo,nombre,unidad_base,activo) values('${id(11)}','MP-ENSAYO','Harina ensayo','KG',true);`)
    const rpc = async (sql, args=[]) => (await db.query(sql,args)).rows[0]?.r
    const hoy = (await db.query("select (now() at time zone 'America/Guayaquil')::date::text f")).rows[0].f
    // Las aperturas MP/PT se prueban además en verificar_arranque_pt_sql.mjs.
    // Este recorrido empieza con MP física inicial y PT vacío.
    await db.exec(`insert into inv_kardex_movimientos(tipo,articulo_id,fecha,clase,cantidad,motivo,responsable)
      values('MATERIA_PRIMA','${id(11)}',current_date-1,'SALDO_INICIAL',100,'Físico de ensayo','Ensayo');`)
    const pt = async () => Number((await db.query('select coalesce(sum(cantidad),0) n from inventario_lotes')).rows[0].n)
    const mp = async () => Number((await db.query("select sum(cantidad) n from inv_kardex_movimientos where tipo='MATERIA_PRIMA'")).rows[0].n)
    const datos = {numeroPedidoCliente:'OC-ENSAYO',clienteId:id(2),bodegaId:id(3),fechaEntrega:hoy,
      horaEntrega:'08:30',prioridad:'NORMAL',tipoEmpaque:'NO DEFINIDO',detalles:[{productoId:id(10),totalUnidades:30,unidadManejo:10}]}
    const pedido = await rpc('select registrar_pedido_seguro($1,$2::jsonb,$3) r',[id(100),JSON.stringify(datos),id(1)])
    await t.test('Repetir pedido conserva una sola orden y el plan incluye sus unidades',async()=>{
      const otro = await rpc('select registrar_pedido_seguro($1,$2::jsonb,$3) r',[id(100),JSON.stringify(datos),id(1)])
      assert.equal(otro.pedido_id,pedido.pedido_id)
      const plan=(await db.query('select * from obtener_produccion_sugerida_periodo($1,$1)',[hoy])).rows[0]
      assert.equal(Number(plan.pedidos_pendientes),30)
      assert.equal(Number(plan.necesidad_neta),30)
      assert.equal(await pt(),0)
    })
    const fabricacion = [{producto_id:id(10),tipo_destino:'PRODUCTO_TERMINADO',numero_paradas:5,tamano_parada:10,
      unidades:50,fecha_produccion:hoy,lote:'ENSAYO',fecha_vencimiento:'2099-12-31',orden:1,
      consumo_mp:{version:1,confirmado:true,referenciaReceta:'Consumo de ensayo',observaciones:'',
        lineas:[{materiaPrimaId:id(11),unidad:'KG',cantidad:20}]}}]
    await t.test('Producción y consumo son atómicos; reintento no duplica inventarios',async()=>{
      const a = await rpc('select registrar_produccion_segura($1,$2,$3::jsonb,$4) r',[id(101),hoy,JSON.stringify(fabricacion),id(1)])
      const b = await rpc('select registrar_produccion_segura($1,$2,$3::jsonb,$4) r',[id(101),hoy,JSON.stringify(fabricacion),id(1)])
      assert.equal(a.produccion_id,b.produccion_id)
      assert.equal(await pt(),50); assert.equal(await mp(),80)
      const invalida=structuredClone(fabricacion); invalida[0].consumo_mp.lineas[0].cantidad=81
      await assert.rejects(()=>rpc('select registrar_produccion_segura($1,$2,$3::jsonb,$4) r',[id(102),hoy,JSON.stringify(invalida),id(1)]),/negativo|insuficiente/i)
      assert.equal(await pt(),50); assert.equal(await mp(),80)
      assert.equal(Number((await db.query('select count(*) n from producciones')).rows[0].n),1)
    })
    const detalle=(await db.query('select id from pedido_detalles where pedido_id=$1',[pedido.pedido_id])).rows[0].id
    let reserva
    await t.test('Preparar y reintentar reserva no descuenta stock físico',async()=>{
      const d={pedidoId:pedido.pedido_id,cantidades:[{pedidoDetalleId:detalle,unidades:30}]}
      const v=await rpc('select prever_operacion_reserva($1,$2::jsonb) r',['PREPARAR',JSON.stringify(d)])
      assert.equal(v.puede_ejecutar,true)
      reserva=await rpc('select ejecutar_operacion_reserva($1,$2,$3::jsonb,$4,$5) r',[id(103),'PREPARAR',JSON.stringify(d),v.token,id(1)])
      const b=await rpc('select ejecutar_operacion_reserva($1,$2,$3::jsonb,$4,$5) r',[id(103),'PREPARAR',JSON.stringify(d),v.token,id(1)])
      assert.equal(reserva.reserva_id,b.reserva_id);assert.equal(await pt(),50)
      assert.equal(Number((await db.query('select cantidad_disponible from stock_disponible_lotes')).rows[0].cantidad_disponible),20)
    })
    await t.test('Despachar y recuperar resultado descuenta una sola vez y vincula documento',async()=>{
      const d={reservaId:reserva.reserva_id,numeroFactura:'FACT-ENSAYO',cantidades:[{pedidoDetalleId:detalle,unidades:30}]}
      const v=await rpc('select prever_operacion_logistica($1,$2::jsonb) r',['DESPACHAR',JSON.stringify(d)])
      assert.equal(v.puede_ejecutar,true)
      await rpc('select ejecutar_operacion_logistica($1,$2,$3::jsonb,$4,$5) r',[id(104),'DESPACHAR',JSON.stringify(d),v.token,id(1)])
      await rpc('select ejecutar_operacion_logistica($1,$2,$3::jsonb,$4,$5) r',[id(104),'DESPACHAR',JSON.stringify(d),v.token,id(1)])
      assert.equal(await pt(),20); assert.equal(await mp(),80)
      const p=(await db.query('select estado from pedidos where id=$1',[pedido.pedido_id])).rows[0]
      assert.equal(p.estado,'DESPACHADO')
      assert.equal(Number((await db.query('select unidades_despachadas n from pedido_detalles where id=$1',[detalle])).rows[0].n),30)
    })
  } finally {await db.close()}
})
