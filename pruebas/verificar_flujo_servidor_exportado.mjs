// certificada de la base ni una migración. Cuerpos de funciones, tipos, columnas,
// checks, claves, triggers y las dos vistas se usan tal como fueron exportados.
function columnaEnsayo(c) {
  let valor = ''
  if (c.tipo === 'uuid' && c.nombre === 'id') valor = ' default gen_random_uuid()'
  else if (c.tipo === 'bigint' && ['id', 'numero_produccion'].includes(c.nombre)) valor = ' generated by default as identity'
  else if (c.tipo === 'timestamp with time zone') valor = ' default now()'
  else if (c.tipo === 'date' && c.no_nulo) valor = ' default current_date'
  else if (c.no_nulo && /^(integer|bigint|numeric)/.test(c.tipo)) valor = ' default 0'
  else if (c.no_nulo && c.tipo === 'text') valor = " default ''"
  else if (c.no_nulo && c.tipo === 'boolean') valor = ' default false'
  return `${nombreSQL(c.nombre)} ${c.tipo}${valor}${c.no_nulo ? ' not null' : ''}`
}

