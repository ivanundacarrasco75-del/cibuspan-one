import test from 'node:test'
import assert from 'node:assert/strict'
import {readFile} from 'node:fs/promises'

const {PGlite} = await import(process.env.CIBUSPAN_SQL_TEST_MODULE || '@electric-sql/pglite')
// El diagnóstico pertenece al usuario y no se publica en el repositorio.
// CIBUSPAN_AUDIT_FILE apunta al JSON privado o al TXT adjuntado con ese JSON.
if (!process.env.CIBUSPAN_AUDIT_FILE) throw new Error('Define CIBUSPAN_AUDIT_FILE con la ruta al diagnóstico privado; no lo subas a Git.')
const documento = JSON.parse((await readFile(process.env.CIBUSPAN_AUDIT_FILE, 'utf8')).replace(/^\uFEFF/, ''))
const referencia = Array.isArray(documento) ? documento[0].auditoria_flujo_operativo : documento
assert.ok(Array.isArray(referencia?.funciones) && Array.isArray(referencia?.objetos), 'Diagnóstico inválido')
const probarAutorizacion = process.env.CIBUSPAN_PROBAR_AUTORIZACION === '1'
const id = n => `00000000-0000-0000-0000-${String(n).padStart(12, '0')}`
const nombreSQL = nombre => '"' + nombre.replaceAll('"', '""') + '"'
const tablas = ['clientes', 'bodegas', 'productos', 'app_profiles', 'materias_primas',
  'inv_cargas_iniciales', 'inv_inicio_octubre', 'inv_kardex_movimientos', 'inventario_lotes',
  'semielaborado_tipos', 'semielaborado_destinos', 'inventario_semielaborados', 'conversiones_semielaborados',
  'pedidos', 'pedido_detalles', 'producciones', 'produccion_detalles', 'reservas_inventario', 'reserva_detalles']
const nombresFunciones = ['app_validar_escritura_modulo', 'actualizar_timestamp', 'actualizar_timestamp_produccion',
  'inv_inicio_proteger_lote', 'inv_inicio_proteger_fecha', 'inv_kardex_observar_pt',
  'registrar_produccion_completa', 'reservar_pedido_fefo_parcial', 'confirmar_despacho_parcial_fefo',
  'liberar_reserva_fefo', 'activar_control_conciliacion_despacho', 'vincular_factura_despacho', 'obtener_produccion_sugerida',
  'editar_produccion_completa', 'ajustar_inventario_lote', 'convertir_inventario_empaque', 'convertir_semielaborado', 'registrar_devolucion_completa']

// El exportador v1 no incluía defaults ni todos los objetos dependientes.
// Estos defaults y auxiliares son del escenario de ensayo, NO una reconstrucción
// certificada de la base ni una migración. Cuerpos de funciones, tipos, columnas,
// checks, claves, triggers y las dos vistas se usan tal como fueron exportados.
function columnaEnsayo(c) {
  let valor = ''
  if (c.tipo === 'uuid' && c.nombre === 'id') valor = ' default gen_random_uuid()'
  else if (c.tipo === 'bigint' && ['id', 'numero_produccion'].includes(c.nombre)) valor = ' generated by default as identity'
  else if (c.tipo === 'timestamp with time zone') valor = ' default now()'
  else if (c.tipo === 'date' && c.no_nulo) valor = ' default current_date'
  else if (c.no_nulo && /^(integer|bigint|numeric)/.test(c.tipo)) valor = ' default 0'
  else if (c.no_nulo && c.tipo === 'text') valor = " default ''"
  else if (c.no_nulo && c.tipo === 'boolean') valor = ' default false'
  return `${nombreSQL(c.nombre)} ${c.tipo}${valor}${c.no_nulo ? ' not null' : ''}`
}

test('Caracterización local de las funciones instaladas exportadas el 23/10/2026', async t => {
  const db = new PGlite()
  try {
    await db.exec(`create schema auth; create role anon; create role authenticated; create role service_role;
      create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$
        select nullif(current_setting('ensayo.usuario',true),'')::uuid $$;
      create function app_puede_alguna(text[]) returns boolean language sql stable as $$
        select current_setting('ensayo.permitido',true)='si' $$;
      create table inv_respaldos_inicio(id uuid primary key,datos jsonb default '{}');
      grant usage on schema public,auth to anon,authenticated,service_role;`)
    const objetos = tablas.map(nombre => {
      const objeto = referencia.objetos.find(o => o.nombre === nombre)
      assert.ok(objeto, `Falta definición exportada de ${nombre}`)
      return objeto
    })
    for (const objeto of objetos) {
      await db.exec(`create table public.${nombreSQL(objeto.nombre)} (${objeto.columnas.map(columnaEnsayo).join(',')})`)
      for (const c of objeto.restricciones || []) {
        if (['c', 'p', 'u'].includes(c.tipo)) {
          await db.exec(`alter table public.${nombreSQL(objeto.nombre)} add constraint ${nombreSQL(c.nombre)} ${c.definicion}`)
        }
      }
    }
    // Todas las FK de estas tablas salvo categorías ajenas a este escenario.
    for (const objeto of objetos) for (const c of objeto.restricciones || []) {
      if (c.tipo === 'f' && !c.definicion.includes('categorias_materia_prima')) {
        await db.exec(`alter table public.${nombreSQL(objeto.nombre)} add constraint ${nombreSQL(c.nombre)} ${c.definicion}`)
      }
    }
    for (const nombre of ['stock_disponible_lotes', 'stock_semielaborados']) {
      await db.exec(`create view public.${nombreSQL(nombre)} as ${referencia.objetos.find(o => o.nombre === nombre).vista.replace(/;\s*$/, '')}`)
    }
    // Esta vista auxiliar no vino en el exportado v1. Los casos de planificación
    // mantienen semielaborados vacíos; no certifican su cálculo o caducidad.
    await db.exec(`create view stock_semielaborados_resumen as
      select producto_base_id,sum(cantidad_disponible)::integer cantidad_disponible
      from stock_semielaborados group by producto_base_id`)
    for (const nombre of nombresFunciones) {
      const f = referencia.funciones.find(f => f.nombre === nombre)
      assert.ok(f, `Falta cuerpo de ${nombre}`)
      await db.exec(f.definicion)
      await db.exec(`revoke execute on function public.${nombreSQL(nombre)}(${f.firma}) from public`)
      for (const p of f.privilegios || []) {
        if (p.puede_ejecutar && ['anon', 'authenticated'].includes(p.rol)) {
          await db.exec(`grant execute on function public.${nombreSQL(nombre)}(${f.firma}) to ${nombreSQL(p.rol)}`)
        }
      }
    }
    // Instala los triggers reales de las tablas ensayadas. RLS se modela por
    // separado: el diagnóstico v1 omitía PERMISSIVE/RESTRICTIVE y grants de tabla.
    for (const o of objetos) for (const trigger of o.triggers || []) {
      assert.equal(trigger.habilitado, 'O')
      await db.exec(trigger.definicion)
    }
    await db.query("select set_config('ensayo.usuario',$1,false),set_config('ensayo.permitido','si',false)", [id(1)])
    await db.exec(`insert into auth.users values ('${id(1)}');
      insert into app_profiles(user_id,email,nombre,rol,activo)
        values ('${id(1)}','ensayo@example.com','Usuario de ensayo','ADMINISTRADOR',true);
      insert into clientes(id) values ('${id(2)}');
      insert into bodegas(id,cliente_id) values ('${id(3)}','${id(2)}');
      insert into productos(id,codigo,nombre,corto,activo,tamano_lote,stock_minimo,vida_util_dias)
        values ('${id(10)}','ENSAYO','Producto de ensayo','Ensayo',true,10,100,30);
      insert into materias_primas(id,codigo,nombre,unidad_base) values ('${id(11)}','MP-ENSAYO','Harina ensayo','KG');
      insert into inv_kardex_movimientos(tipo,articulo_id,fecha,clase,cantidad,motivo,responsable)
        values ('MATERIA_PRIMA','${id(11)}',current_date,'SALDO_INICIAL',100,'Escenario aislado','Prueba');`)
    if (probarAutorizacion) {
      const antes = (await db.query('select (select count(*) from inventario_lotes)::int lotes,(select count(*) from inv_kardex_movimientos)::int movimientos')).rows[0]
      await db.exec(await readFile(new URL('../supabase/migrations/202610230001_autorizacion_operativa.sql', import.meta.url), 'utf8'))
      assert.deepEqual((await db.query('select (select count(*) from inventario_lotes)::int lotes,(select count(*) from inv_kardex_movimientos)::int movimientos')).rows[0], antes)
    }
    const hoy = (await db.query('select current_date::text hoy')).rows[0].hoy
    const detalleProduccion = cambios => ({producto_id: id(10), tipo_destino: 'PRODUCTO_TERMINADO',
      numero_paradas: 5, tamano_parada: 10, unidades: 50, fecha_produccion: hoy,
      lote: 'ENSAYO', fecha_vencimiento: '2099-12-31', orden: 1, ...cambios})
    const producir = detalles => db.query('select registrar_produccion_completa($1,$2::jsonb) id', [hoy, JSON.stringify(detalles || [detalleProduccion()])])
    const cantidad = async () => Number((await db.query('select coalesce(sum(cantidad),0) n from inventario_lotes')).rows[0].n)
    const movimientos = async () => Number((await db.query("select count(*) n from inv_kardex_movimientos where tipo='PRODUCTO_TERMINADO'")).rows[0].n)
    const stock = async () => (await db.query('select cantidad_fisica,cantidad_reservada,cantidad_disponible from stock_disponible_lotes')).rows[0]
    const crearPedido = () => db.exec(`insert into pedidos(id,cliente_id,bodega_id,fecha_entrega,estado,total_unidades,creado_por)
      values ('PED-ENSAYO','${id(2)}','${id(3)}',current_date,'INGRESADO',30,'${id(1)}');
      insert into pedido_detalles(id,pedido_id,producto_id,total_unidades,unidades_manejo,unidades_despachadas,estado)
      values ('${id(20)}','PED-ENSAYO','${id(10)}',30,10,0,'PENDIENTE');`)
    const cantidades = unidades => JSON.stringify([{pedido_detalle_id: id(20), unidades}])
    const preparar = async (unidades = 20) => (await db.query('select reservar_pedido_fefo_parcial($1,$2::jsonb) id', ['PED-ENSAYO', cantidades(unidades)])).rows[0].id
    const confirmar = (reserva, unidades = 20) => db.query('select confirmar_despacho_parcial_fefo($1,$2::jsonb) id', [reserva, cantidades(unidades)])
    const rechazaSinAbortar = async (operacion, patron) => {
      await db.exec('savepoint intento')
      try { await assert.rejects(operacion, patron) }
      finally { await db.exec('rollback to savepoint intento; release savepoint intento') }
    }
    const caso = (nombre, fn) => t.test(nombre, async () => {
      await db.exec('begin')
      try { await fn() }
      finally { await db.exec('reset role; rollback') }
    })

    await caso('Producción suma PT y Kardex PT; no genera consumo de MP', async () => {
      await producir()
      assert.equal(await cantidad(), 50)
      assert.equal(await movimientos(), 1)
      assert.equal(Number((await db.query("select sum(cantidad) n from inv_kardex_movimientos where tipo='MATERIA_PRIMA'")).rows[0].n), 100)
      assert.equal(Number((await db.query("select count(*) n from inv_kardex_movimientos where tipo='MATERIA_PRIMA'")).rows[0].n), 1)
    })
    await caso('Un segundo envío idéntico de producción vuelve a sumar existencias', async () => {
      const primero = (await producir()).rows[0].id
      const segundo = (await producir()).rows[0].id
      assert.notEqual(primero, segundo)
      assert.equal(await cantidad(), 100)
      assert.equal(await movimientos(), 2)
    })
    await caso('Un detalle inválido revierte toda la producción y su Kardex', async () => {
      await rechazaSinAbortar(() => producir([detalleProduccion(), detalleProduccion({unidades: 0})]), /unidades/)
      assert.equal(await cantidad(), 0)
      assert.equal(await movimientos(), 0)
      assert.equal(Number((await db.query('select count(*) n from producciones')).rows[0].n), 0)
    })
    await caso('Preparar reserva sin salida física; liberar recupera disponibilidad', async () => {
      await producir(); await crearPedido()
      const reserva = await preparar()
      assert.deepEqual(await stock(), {cantidad_fisica: 50, cantidad_reservada: 20, cantidad_disponible: 30})
      assert.equal(await movimientos(), 1)
      await rechazaSinAbortar(() => preparar(), /INGRESADO|reserva activa/)
      await db.query('select liberar_reserva_fefo($1::uuid)', [reserva])
      assert.deepEqual(await stock(), {cantidad_fisica: 50, cantidad_reservada: 0, cantidad_disponible: 50})
      assert.equal(await movimientos(), 1)
      assert.equal((await db.query("select estado from pedidos where id='PED-ENSAYO'")).rows[0].estado, 'INGRESADO')
    })
    await caso('Confirmar parcial descuenta una vez y cierra el pedido con faltante', async () => {
      await producir(); await crearPedido()
      const reserva = await preparar()
      await confirmar(reserva)
      assert.deepEqual(await stock(), {cantidad_fisica: 30, cantidad_reservada: 0, cantidad_disponible: 30})
      assert.equal(await movimientos(), 2)
      assert.equal((await db.query("select estado from pedidos where id='PED-ENSAYO'")).rows[0].estado, 'DESPACHADO')
      assert.deepEqual((await db.query('select total_unidades,unidades_despachadas from pedido_detalles')).rows[0], {total_unidades: 30, unidades_despachadas: 20})
      assert.equal((await db.query('select pedidos_pendientes from obtener_produccion_sugerida()')).rows[0].pedidos_pendientes, 0)
      await rechazaSinAbortar(() => confirmar(reserva), /ya fue despachada/)
      assert.equal(await cantidad(), 30); assert.equal(await movimientos(), 2)
    })
    await caso('Factura y conciliación previas permanecen aunque falle confirmar', async () => {
      await producir(); await crearPedido()
      const reserva = await preparar()
      await db.query('select activar_control_conciliacion_despacho($1)', [reserva])
      await db.query('select vincular_factura_despacho($1,$2)', [reserva, 'FAC-ENSAYO'])
      await rechazaSinAbortar(() => confirmar(reserva, 30), /reservadas/)
      assert.equal(await cantidad(), 50)
      assert.equal(await movimientos(), 1)
      assert.deepEqual((await db.query('select estado,numero_factura,conciliacion_aplica from reservas_inventario')).rows[0],
        {estado: 'ACTIVA', numero_factura: 'FAC-ENSAYO', conciliacion_aplica: true})
    })
    await caso('Stock mínimo configurado no aumenta la sugerencia sin pedidos', async () => {
      const sugerencia = (await db.query('select stock_minimo,necesidad_neta,unidades_sugeridas from obtener_produccion_sugerida()')).rows[0]
      assert.deepEqual(sugerencia, {stock_minimo: 100, necesidad_neta: 0, unidades_sugeridas: 0})
    })
    await caso('La estructura exportada permite dos pedidos con el mismo número', async () => {
      const indices = referencia.objetos.find(o => o.nombre === 'pedidos').indices
      assert.equal(indices.filter(i => i.includes('UNIQUE')).length, 1)
      assert.ok(indices[0].includes('(id)'))
      await crearPedido()
      await db.exec(`update pedidos set numero_pedido_cliente='NUM-ENSAYO';
        insert into pedidos(id,cliente_id,bodega_id,fecha_entrega,estado,total_unidades,creado_por,numero_pedido_cliente)
        values ('PED-OTRO','${id(2)}','${id(3)}',current_date,'INGRESADO',30,'${id(1)}','NUM-ENSAYO');`)
      assert.equal(Number((await db.query("select count(*) n from pedidos where numero_pedido_cliente='NUM-ENSAYO'")).rows[0].n), 2)
    })
    await caso('Usuario autenticado sin permiso queda bloqueado por el control del servidor', async () => {
      await db.exec("select set_config('ensayo.permitido','no',false); set role authenticated")
      await rechazaSinAbortar(() => producir(), /permiso/)
      await db.exec('reset role')
      assert.equal(await cantidad(), 0)
    })
    if (probarAutorizacion) {
      await caso('La corrección aplicada al exportado bloquea acceso sin sesión y mantiene PT intacto', async () => {
        await db.exec("select set_config('ensayo.usuario','',false); set role anon")
        await rechazaSinAbortar(() => producir(), e => e.code === '42501')
        await db.exec('reset role; set role authenticated')
        await rechazaSinAbortar(() => producir(), e => e.code === '42501')
        await db.exec('reset role')
        assert.equal(await cantidad(), 0); assert.equal(await movimientos(), 0)
      })
      await caso('Un proceso service_role conserva registro válido y consulta de planificación', async () => {
        await db.exec("select set_config('ensayo.usuario','',false); set role service_role")
        await producir()
        const plan = await db.query('select * from obtener_produccion_sugerida()')
        assert.equal(plan.rows.length, 1)
        assert.equal(plan.rows[0].inventario_disponible, 50)
        await db.exec('reset role')
        assert.equal(await cantidad(), 50); assert.equal(await movimientos(), 1)
      })
    }
  } finally { await db.close() }
})
