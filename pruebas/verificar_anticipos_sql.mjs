import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"
import test from "node:test"
import { PGlite } from "@electric-sql/pglite"
const leer = nombre => readFile(new URL("../supabase/migrations/"+nombre+".sql",import.meta.url),"utf8")
const uid = "aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa"
const id = n => "00000000-0000-0000-0000-"+String(n).padStart(12,"0")
const clave = n => String(n).repeat(49)

async function preparar(t) {
  const db = new PGlite()
  t.after(()=>db.close())
  await db.exec(`
    create role anon; create role authenticated; create schema auth;
    create table auth.users(id uuid primary key); insert into auth.users values('${uid}');
    create function auth.uid() returns uuid language sql stable as $$ select '${uid}'::uuid $$;
    grant usage on schema auth to authenticated;
    create table app_profiles(user_id uuid primary key,rol text,activo boolean);
    create table app_user_permissions(user_id uuid,pantalla text,permitido boolean,primary key(user_id,pantalla));
    create table app_audit_log(id bigint generated by default as identity primary key,actor_user_id uuid,target_user_id uuid,
      accion text not null,detalle jsonb,creado_en timestamptz default now());
    insert into app_profiles values('${uid}','JEFA_FACTURACION',true);
    insert into app_user_permissions values('${uid}','Administración',false),
      ('${uid}','Pagos y Finanzas · Cuentas por Pagar',true),('${uid}','Pagos y Finanzas · Pagos semanales',true),
      ('${uid}','Compras · Facturas del SRI',true);
    create function app_es_admin() returns boolean language sql stable security definer set search_path='' as
      $$ select exists(select 1 from public.app_profiles where user_id=auth.uid() and activo and rol='ADMINISTRADOR') $$;
    create function app_puede(text) returns boolean language sql stable security definer set search_path='' as
      $$ select coalesce((select permitido from public.app_user_permissions where user_id=auth.uid() and pantalla=$1),public.app_es_admin()) $$;
    create function app_puede_alguna(text[]) returns boolean language sql stable security definer set search_path='' as
      $$ select coalesce(bool_or(public.app_puede(ruta)),false) from unnest($1) ruta $$;
    create function fin_normalizar_texto(text) returns text language sql immutable as $$ select upper(btrim($1)) $$;
    create function inv_kardex_puede(text) returns boolean language sql as $$ select false $$;
    create table compras_recepciones_mp(id uuid); alter table compras_recepciones_mp enable row level security;
    create policy compras_recepciones_mp_lectura on compras_recepciones_mp for select using(false);
    create table historico(id uuid,periodo date,fecha_documento date,numero_documento text,proveedor text,
      concepto text,valor numeric,observaciones text,cuenta_codigo text,tipo_documento text);
    create view fin_vw_resultado_clasificacion_detalle as select * from historico;
    grant select on fin_vw_resultado_clasificacion_detalle to authenticated;
  `)
  for (const nombre of ["202611140001_compras_sri","202611150001_compras_sri_edicion_abonos",
    "202611170001_compras_documentos_manuales","202611170003_fin_cuentas_por_pagar_compras",
    "202611170004_compras_excel_anual","202608150110_roles_pago_mensuales","202611180001_nomina_programacion_personal",
    "202611180002_nomina_cuentas_por_pagar","202611200001_compras_sri_permisos",
    "202611200002_finanzas_permisos_asignados","202611200003_finanzas_seleccion_por_modulo"]) await db.exec(await leer(nombre))
  const migracion=await leer("202611200004_anticipos_proveedores")
  await db.exec(migracion)
  await db.exec(migracion)
  for (let n=1;n<=3;n++) await db.query(
    "insert into compras_sri(clave_acceso,fecha_emision,datos,xml_original) values($1,'2026-11-20',$2,'<xml/>')",
    [clave(n),JSON.stringify({clave:clave(n),serie:"F-"+n,fecha:"2026-11-20",proveedor:"Proveedor Prueba",ruc:n===3?"9999999999001":"1790000000001",total:"300",subtotal:"300",items:[],impuestos:[]})])
  await db.exec("set role authenticated")
  const crear=(n,monto="300")=>db.query("select fin_guardar_anticipo($1,'2026-11-20','Proveedor Prueba','1790000000001','Materiales',$2)",[id(n),monto])
  const programar=(documento,monto)=>db.query("select fin_programar_compras('2026-11-16',$1)",[JSON.stringify([{id:documento,monto}])])
  const pagar=(documento,n,monto,semana="2026-11-16")=>db.query(
    "select fin_pagar_compra($1,$2,$3,'2026-11-20','DEP-PRUEBA',$4,false)",[documento,id(n),monto,semana])
  const cruzar=(n,anticipo,factura,monto)=>db.query("select fin_aplicar_anticipo($1,$2,$3,$4,true)",[id(n),id(anticipo),factura,monto])
  const cuenta=async documento=>(await db.query("select pagado::numeric,saldo::numeric from fin_consultar_cuentas() where id=$1",[documento])).rows[0]
  return {db,crear,programar,pagar,cruzar,cuenta}
}

test("paga el anticipo una sola vez y su cruce completo deja pagada la factura de Finanzas y SRI",async t=>{
  const {db,crear,programar,pagar,cruzar,cuenta}=await preparar(t)
  await crear(10); await crear(10)
  await programar("anticipo:"+id(10),300)
  await pagar("anticipo:"+id(10),20,300)
  await pagar("anticipo:"+id(10),20,300)
  assert.deepEqual(await cuenta("anticipo:"+id(10)),{pagado:"300.00",saldo:"0.00"})
  await cruzar(30,10,"sri:"+clave(1),300)
  await cruzar(30,10,"sri:"+clave(1),300)
  assert.deepEqual(await cuenta("sri:"+clave(1)),{pagado:"300.00",saldo:"0.00"})
  const pagos=(await db.query("select abonos from compras_vw_facturas where id=$1",["sri:"+clave(1)])).rows[0].abonos
  assert.equal(pagos.length,1)
  assert.equal(pagos[0].clase,"APLICACION_ANTICIPO")
  assert.match(pagos[0].documento,/DEP-PRUEBA/)
  await assert.rejects(db.query("select compras_sri_editar($1,'total','299')",[clave(1)]),/abonos registrados/)
  const editado=(await db.query("select compras_sri_editar($1,'descripcion','Texto editado') as resultado",[clave(1)])).rows[0].resultado
  assert.equal(editado.abonos.length,1)
  await db.exec("reset role")
  assert.equal((await db.query("select count(*)::int n from fin_pagos_compras")).rows[0].n,1)
  assert.equal((await db.query("select count(*)::int n from app_audit_log")).rows[0].n,1)
})

test("cruce parcial conserva crédito, evita sobrepago, valida proveedor y reduce una programación de factura pendiente",async t=>{
  const {db,crear,programar,pagar,cruzar,cuenta}=await preparar(t)
  await crear(10,"400")
  await assert.rejects(cruzar(30,10,"sri:"+clave(1),100),/pagado disponible/)
  await programar("anticipo:"+id(10),400)
  await pagar("anticipo:"+id(10),20,400)
  await assert.rejects(cruzar(30,10,"sri:"+clave(3),100),/identificación/)
  await programar("sri:"+clave(1),300)
  await cruzar(30,10,"sri:"+clave(1),100)
  assert.deepEqual(await cuenta("sri:"+clave(1)),{pagado:"100.00",saldo:"200.00"})
  const plan=(await db.query("select monto::text from fin_consultar_programaciones() where documento_id=$1",["sri:"+clave(1)])).rows[0]
  assert.equal(plan.monto,"200.00")
  await assert.rejects(cruzar(30,10,"sri:"+clave(1),101),/otros datos/)
  await assert.rejects(cruzar(31,10,"sri:"+clave(1),201),/supera su saldo/)
  await assert.rejects(pagar("sri:"+clave(1),21,201),/saldo/)
  await cruzar(31,10,"sri:"+clave(1),200)
  assert.deepEqual(await cuenta("sri:"+clave(1)),{pagado:"300.00",saldo:"0.00"})
  assert.equal((await db.query("select count(*)::int n from fin_consultar_programaciones() where documento_id=$1",["sri:"+clave(1)])).rows[0].n,0)
  await cruzar(32,10,"sri:"+clave(2),100)
  assert.deepEqual(await cuenta("sri:"+clave(2)),{pagado:"100.00",saldo:"200.00"})
  await assert.rejects(cruzar(33,10,"sri:"+clave(2),1),/pagado disponible/)
  assert.equal((await db.query("select disponible::text from fin_consultar_anticipos()")).rows[0].disponible,"0.00")
})

test("revocar el permiso cierra el alta y el cruce, y el rol anónimo no puede operar",async t=>{
  const {db,crear,cruzar}=await preparar(t)
  await db.exec("reset role; update app_user_permissions set permitido=false; set role authenticated")
  await assert.rejects(crear(10),/permiso/)
  await assert.rejects(cruzar(30,10,"sri:"+clave(1),100),/permiso/)
  await assert.rejects(db.query("select * from fin_consultar_anticipos()"),/permiso/)
  await db.exec("set role anon")
  await assert.rejects(crear(10),/permission denied/)
})

