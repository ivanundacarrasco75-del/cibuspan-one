test('El anticipo se cruza contra el neto retenido; una factura mixta admite varias bases de renta',async t=>{
  const {db,cuenta,aplicar}=await preparar(t)
  await db.query("select fin_guardar_anticipo($1,'2026-11-01','Proveedor','1790000000001','Anticipo',108.5)",[id(30)])
  await db.query("select fin_programar_compras('2026-11-16',$1)",[JSON.stringify([{id:'anticipo:'+id(30),monto:108.5}])])
  await db.query("select fin_pagar_compra($1,$2,108.5,'2026-11-20','DEP-ANT','2026-11-16',false)",['anticipo:'+id(30),id(31)])
  await aplicar()
  await assert.rejects(db.query('select fin_aplicar_anticipo($1,$2,$3,109,true)',[id(32),id(30),'sri:'+clave]),/importe pagado disponible/)
  await db.query('select fin_aplicar_anticipo($1,$2,$3,108.5,true)',[id(32),id(30),'sri:'+clave])
  assert.equal(Number((await cuenta()).saldo),0)
  await db.query("select fin_anular_retencion($1,'Corregir clasificación de compra')",[id(10)])
  assert.equal(Number((await cuenta()).saldo),6.5)
  // La nueva retención sumaría 7, superior al saldo conciliable: no debe guardarse.
  await assert.rejects(aplicar(11,undefined,'GENERAL',false,[{regla:'IR_BIENES_2026',base:50},{regla:'IVA_BIENES',base:15},{regla:'IR_MANO_OBRA_2026',base:50}]),/menor que los pagos/)
  await aplicar(11,undefined,'GENERAL',false,[{regla:'IR_BIENES_2026',base:50},{regla:'IVA_BIENES',base:15},{regla:'IR_TRANSPORTE_2026',base:50}])
  assert.equal(Number((await cuenta()).saldo),0.5)
})

