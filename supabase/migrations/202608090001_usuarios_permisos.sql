create or replace function public.app_es_admin(p_user_id uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.app_profiles p
    where p.user_id = p_user_id
      and p.activo
      and p.rol = 'ADMINISTRADOR'
  );
$$;

create or replace function public.app_puede(
  p_pantalla text,
  p_user_id uuid default auth.uid()
)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select case
    when p_pantalla = 'Usuarios y permisos' then public.app_es_admin(p_user_id)
    else coalesce(
      (
        select up.permitido
        from public.app_user_permissions up
        where up.user_id = p_user_id and up.pantalla = p_pantalla
      ),
      (
        select rp.permitido
        from public.app_profiles p
        join public.app_role_permissions rp on rp.rol = p.rol
        where p.user_id = p_user_id
          and p.activo
          and rp.pantalla = p_pantalla
      ),
      false
    )
  end;
$$;

create or replace function public.app_mis_permisos()
returns table (pantalla text, permitido boolean)
language sql
stable
security definer
set search_path = public
as $$
  with pantallas as (
    select rp.pantalla
    from public.app_profiles p
    join public.app_role_permissions rp on rp.rol = p.rol
    where p.user_id = auth.uid() and p.activo
    union
    select up.pantalla
    from public.app_user_permissions up
    where up.user_id = auth.uid()
  )
  select
    ps.pantalla,
    case
      when ps.pantalla = 'Usuarios y permisos' then public.app_es_admin()
      else coalesce(
        (select up.permitido from public.app_user_permissions up
         where up.user_id = auth.uid() and up.pantalla = ps.pantalla),
        (select rp.permitido
         from public.app_profiles p
         join public.app_role_permissions rp on rp.rol = p.rol
         where p.user_id = auth.uid() and rp.pantalla = ps.pantalla),
        false
      )
    end as permitido
  from pantallas ps
  order by ps.pantalla;
$$;

