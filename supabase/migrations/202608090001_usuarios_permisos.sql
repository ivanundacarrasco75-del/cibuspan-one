create table if not exists public.app_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  nombre text,
  rol text not null default 'BODEGUERO' check (rol in (
    'ADMINISTRADOR', 'GERENTE', 'BODEGUERO',
    'GERENTE_OPERACIONES', 'JEFA_FACTURACION'
  )),
  activo boolean not null default true,
  creado_en timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);

create table if not exists public.app_role_permissions (
  rol text not null check (rol in (
    'ADMINISTRADOR', 'GERENTE', 'BODEGUERO',
    'GERENTE_OPERACIONES', 'JEFA_FACTURACION'
  )),
  pantalla text not null,
  permitido boolean not null default true,
  primary key (rol, pantalla)
);

create table if not exists public.app_user_permissions (
  user_id uuid not null references auth.users(id) on delete cascade,
  pantalla text not null,
  permitido boolean not null,
  actualizado_en timestamptz not null default now(),
  actualizado_por uuid references auth.users(id) on delete set null,
  primary key (user_id, pantalla)
);

create table if not exists public.app_audit_log (
  id bigint generated by default as identity primary key,
  actor_user_id uuid references auth.users(id) on delete set null,
  target_user_id uuid references auth.users(id) on delete set null,
  accion text not null,
  detalle jsonb,
  creado_en timestamptz not null default now()
);

create or replace function public.app_handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  rol_inicial text;
begin
  rol_inicial := case
    when new.raw_user_meta_data ->> 'rol' in (
      'ADMINISTRADOR', 'GERENTE', 'BODEGUERO',
      'GERENTE_OPERACIONES', 'JEFA_FACTURACION'
    ) then new.raw_user_meta_data ->> 'rol'
    else 'BODEGUERO'
  end;

  insert into public.app_profiles (user_id, email, nombre, rol)
  values (
    new.id,
    coalesce(new.email, ''),
    nullif(new.raw_user_meta_data ->> 'nombre', ''),
    rol_inicial
  )
  on conflict (user_id) do update set
    email = excluded.email,
    nombre = coalesce(excluded.nombre, public.app_profiles.nombre),
    actualizado_en = now();

  return new;
end;
$$;

drop trigger if exists on_auth_user_created_app_profile on auth.users;
create trigger on_auth_user_created_app_profile
after insert or update of email, raw_user_meta_data on auth.users
for each row execute procedure public.app_handle_new_user();

-- Crea perfiles para usuarios que ya existían antes de instalar esta migración.
insert into public.app_profiles (user_id, email, nombre, rol)
select
  u.id,
  coalesce(u.email, ''),
  nullif(u.raw_user_meta_data ->> 'nombre', ''),
  case
    when u.raw_user_meta_data ->> 'rol' in (
      'ADMINISTRADOR', 'GERENTE', 'BODEGUERO',
      'GERENTE_OPERACIONES', 'JEFA_FACTURACION'
    ) then u.raw_user_meta_data ->> 'rol'
    else 'BODEGUERO'
  end
from auth.users u
on conflict (user_id) do update set email = excluded.email;

-- El usuario más antiguo queda como administrador inicial si todavía no existe uno.
update public.app_profiles
set rol = 'ADMINISTRADOR', actualizado_en = now()
where user_id = (
  select u.id from auth.users u order by u.created_at asc limit 1
)
and not exists (
  select 1 from public.app_profiles where rol = 'ADMINISTRADOR'
);

delete from public.app_role_permissions;

