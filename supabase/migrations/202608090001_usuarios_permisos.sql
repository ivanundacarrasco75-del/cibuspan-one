drop policy if exists app_profiles_lectura on public.app_profiles;
create policy app_profiles_lectura on public.app_profiles
for select to authenticated
using (user_id = auth.uid() or public.app_es_admin());

drop policy if exists app_profiles_admin_actualiza on public.app_profiles;
create policy app_profiles_admin_actualiza on public.app_profiles
for update to authenticated
using (public.app_es_admin())
with check (public.app_es_admin());

drop policy if exists app_roles_lectura on public.app_role_permissions;
create policy app_roles_lectura on public.app_role_permissions
for select to authenticated using (true);

drop policy if exists app_permisos_lectura on public.app_user_permissions;
create policy app_permisos_lectura on public.app_user_permissions
for select to authenticated
using (user_id = auth.uid() or public.app_es_admin());

drop policy if exists app_permisos_admin on public.app_user_permissions;
create policy app_permisos_admin on public.app_user_permissions
for all to authenticated
using (public.app_es_admin())
with check (public.app_es_admin());

drop policy if exists app_auditoria_admin_lectura on public.app_audit_log;
create policy app_auditoria_admin_lectura on public.app_audit_log
for select to authenticated using (public.app_es_admin());

